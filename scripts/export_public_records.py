#!/usr/bin/env python3
"""Export approved public case fields from canonical case-state records.

The exporter deliberately excludes private intake, admin, customer, and reviewer
data. Generated files are deterministic: no wall-clock timestamp is embedded.
"""

from __future__ import annotations

import html
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
BASE_URL = "https://structurevidence.org"


def load(relative: str) -> dict:
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


def write_json(relative: str, value: object) -> None:
    content = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    for path in [ROOT / relative, ROOT / "docs" / relative]:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def yaml_quote(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def write_case_yaml(slug: str, case: dict) -> None:
    fields = [
        ("case_id", case["case_id"]),
        ("title", case["title"]),
        ("canonical_url", case["canonical_url"]),
        ("question", case["question"]),
        ("current_state", case["current_state"]),
        ("as_of", case["as_of"]),
        ("last_material_change", case["last_material_change"]),
        ("evidence_count", len(case["evidence"])),
        ("counter_evidence_count", len(case["counter_evidence"])),
        ("unknown_count", len(case["unknowns"])),
    ]
    text = "# Generated by scripts/export_public_records.py; do not edit manually.\n"
    text += "\n".join(f"{key}: {yaml_quote(value)}" for key, value in fields) + "\n"
    for path in [ROOT / "cases" / slug / "case.yaml", ROOT / "docs" / "cases" / slug / "case.yaml"]:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


