def main() -> None:
    cases = build_cases()
    for slug, case in cases.items():
        public = {key: case[key] for key in ["case_id", "title", "canonical_url", "question", "answer", "current_state", "as_of", "last_material_change", "evidence", "counter_evidence", "unknowns", "search_provenance", "history"]}
        write_json(f"cases/{slug}/index.json", public)
        write_case_yaml(slug, public)
        for key in ["evidence", "counter_evidence", "unknowns", "search_provenance"]:
            write_json(f"cases/{slug}/{key}.json", public[key])
        write_json(f"cases/{slug}/state_history.json", public["history"])
        readme = (
            f"# {case['title']}\n\nCanonical record: {case['canonical_url']}\n\n"
            "Files in this directory are public verification exports. `index.json`, `case.yaml`, and the component JSON files are generated by `scripts/export_public_records.py`.\n"
        )
        for path in [ROOT / "cases" / slug / "README.md", ROOT / "docs" / "cases" / slug / "README.md"]:
            path.write_text(readme, encoding="utf-8")
        for record in case["evidence"]:
            route = ROOT / "e" / record["evidence_id"]
            route.mkdir(parents=True, exist_ok=True)
            write_json(f"e/{record['evidence_id']}/index.json", {**record, "parent_case": case["case_id"], "parent_case_url": case["canonical_url"], "canonical_url": f"{BASE_URL}/e/{record['evidence_id']}/"})
            content = evidence_html(case, record)
            (route / "index.html").write_text(content, encoding="utf-8")
            docs_route = ROOT / "docs" / "e" / record["evidence_id"]
            docs_route.mkdir(parents=True, exist_ok=True)
            (docs_route / "index.html").write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
